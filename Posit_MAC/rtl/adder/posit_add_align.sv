module posit_add_align (
    input logic a_sign,
    input logic a_is_zero,
    input logic a_is_nar,
    input logic signed [10:0] a_sf,
    input logic [25:0] a_frac,
    input logic b_sign,
    input logic b_is_zero,
    input logic b_is_nar,
    input logic signed [10:0] b_sf,
    input logic [25:0] b_frac,
    input logic [4:0] flags_in,
    output logic [30:0] x,
    output logic [30:0] y,
    output logic subtract,
    output logic sign_base,
    output logic signed [10:0] sf_base,
    output logic alignment_tail,
    output logic is_zero,
    output logic is_nar,
    output logic [4:0] flags_o
);
    // Fixed posit32/ES3 elaboration; no public parameters.
    // NB: 32 (original).
    localparam int NB = 32;
    // ES: 2 (original).
    localparam int ES = 3;
    // F: NB - 3 - ES (original).
    localparam int F = 26;
    // SF_W: $clog2(64'd4 * (longint'(NB) - 64'd2) * (64'd1 << ES) + 64'd4) + 1 (original).
    localparam int SF_W = 11;

    localparam int ADD_W = 31; // F + 5
    localparam int SHIFT_W = 5; // $clog2(ADD_W)
    localparam int LOOKUP_W = 32; // 1 << SHIFT_W
    typedef logic [ADD_W-1:0] word_t;
    typedef logic signed [SF_W:0] delta_t;
    typedef logic [SHIFT_W-1:0] shift_t;

    wire [ADD_W-1:0] seed_a;
    wire [ADD_W-1:0] seed_b;
    wire [ADD_W-2:0] shift_seed;
    wire [ADD_W-2:0] shifted_upper;
    wire fill_val = 1'b0;
    wire signed [SF_W:0] diff_ab;
    wire signed [SF_W:0] diff_ba;
    wire sf_a_lt_b;
    wire sf_equal;
    wire frac_a_ge_b;
    wire choose_a;
    wire both_nonzero;
    wire clamp_ab;
    wire clamp_ba;
    wire clamped;
    wire [SHIFT_W-1:0] shift_ab;
    wire [SHIFT_W-1:0] shift_ba;
    wire [SHIFT_W-1:0] shift_amount;
    wire [F+3:0] lo_or_a;
    wire [F+3:0] lo_or_b;
    wire [LOOKUP_W-1:0] tail_a;
    wire [LOOKUP_W-1:0] tail_b;
    wire [LOOKUP_W-1:0] jam_a;
    wire [LOOKUP_W-1:0] jam_b;
    wire tail_ab;
    wire tail_ba;
    wire jam_ab;
    wire jam_ba;
    wire lost_tail;
    wire jam_bit;
    wire [ADD_W-1:0] equal_small;
    wire [ADD_W-1:0] aligned_small;

    generate
        if (F != NB - 3 - ES || F < 2 || NB > 32 || NB < 4 || ES < 0
            || SF_W < $clog2(64'd4 * (longint'(NB) - 64'd2)
                * (64'd1 << ES) + 64'd4) + 1) begin : g_invalid
            initial $fatal(1, "posit_add_align: unsupported parameters");
        end
    endgenerate

    // Full signed precision is retained before either subtraction.
    assign diff_ab = delta_t'(a_sf) - delta_t'(b_sf);
    assign diff_ba = delta_t'(b_sf) - delta_t'(a_sf);
    assign sf_a_lt_b = diff_ab[SF_W];
    assign sf_equal = a_sf == b_sf;
    // The unselected negative difference must never assert clamp.
    // F+2 fits SHIFT_W because F+2 < ADD_W <= 2**SHIFT_W.
    assign clamp_ab = !diff_ab[SF_W]
                    && ((|diff_ab[SF_W-1:SHIFT_W])
                        || (diff_ab[SHIFT_W-1:0] > shift_t'(F+2)));
    assign clamp_ba = !diff_ba[SF_W]
                    && ((|diff_ba[SF_W-1:SHIFT_W])
                        || (diff_ba[SHIFT_W-1:0] > shift_t'(F+2)));

    // A clamped result is overridden at the output; do not put clamp
    // on either the shifter-control path or the parallel table lookups.
    assign shift_ab = diff_ab[SHIFT_W-1:0];
    assign shift_ba = diff_ba[SHIFT_W-1:0];
    assign shift_amount = sf_a_lt_b ? shift_ba : shift_ab;
    assign clamped = sf_a_lt_b ? clamp_ba : clamp_ab;

    assign seed_a = {1'b0, 1'b1, a_frac, 3'b000};
    assign seed_b = {1'b0, 1'b1, b_frac, 3'b000};
    assign frac_a_ge_b = a_frac >= b_frac;
    assign both_nonzero = !a_is_zero && !b_is_zero;
    assign choose_a = !a_is_zero
                    && (b_is_zero || (!sf_a_lt_b && (!sf_equal || frac_a_ge_b)));

    // Shifter data selection NEVER depends on the fraction comparison.
    // Bit0 is generated by a parallel prefix lookup, so shift only upper bits.
    assign shift_seed = sf_a_lt_b ? seed_a[ADD_W-1:1]
                                 : seed_b[ADD_W-1:1];
    dyn_right_shifter  u_align_shift (
        .in(shift_seed),
        .b(shift_amount),
        .fill_val(fill_val),
        .out(shifted_upper)
    );

    // Fixed reduction expressions, not a serial lo_or[k-1] recurrence.
    // seed[2:0]=0. Effective nonclamped shift <=F+2; larger raw shifts are overridden.
    generate
        for (genvar k = 0; k <= F+3; k = k+1) begin : g_prefix
            if (k <= 3) begin : g_zero
                assign lo_or_a[k] = 1'b0;
                assign lo_or_b[k] = 1'b0;
            end else begin : g_fraction
                assign lo_or_a[k] = |a_frac[k-4:0];
                assign lo_or_b[k] = |b_frac[k-4:0];
            end
        end
        // Padding keeps dynamic bit-select width valid for every legal F.
        // jam[s]=lo_or[s+1] is fixed wiring: no run-time index increment.
        for (genvar k = 0; k < LOOKUP_W; k = k+1) begin : g_lookup
            if (k <= F+2) begin : g_live
                assign tail_a[k] = lo_or_a[k];
                assign tail_b[k] = lo_or_b[k];
                assign jam_a[k] = lo_or_a[k+1];
                assign jam_b[k] = lo_or_b[k+1];
            end else begin : g_pad
                assign tail_a[k] = 1'b0;
                assign tail_b[k] = 1'b0;
                assign jam_a[k] = 1'b0;
                assign jam_b[k] = 1'b0;
            end
        end
    endgenerate
    // Each lookup waits only for its own low subtraction bits.
    // The full-width sign selects results after both branches run in parallel.
    assign tail_ab = tail_b[shift_ab];
    assign tail_ba = tail_a[shift_ba];
    assign jam_ab = jam_b[shift_ab];
    assign jam_ba = jam_a[shift_ba];
    assign lost_tail = sf_a_lt_b ? tail_ba : tail_ab;
    assign jam_bit = sf_a_lt_b ? jam_ba : jam_ab;
    assign equal_small = frac_a_ge_b ? seed_b : seed_a;
    assign aligned_small = {shifted_upper, jam_bit};

    always_comb begin
        x = choose_a ? seed_a : seed_b;
        sf_base = choose_a ? a_sf : b_sf;
        sign_base = choose_a ? a_sign : b_sign;
        y = '0;
        subtract = both_nonzero && (a_sign != b_sign);
        alignment_tail = 1'b0;
        is_zero = a_is_zero && b_is_zero;
        is_nar = a_is_nar || b_is_nar || flags_in[4];
        flags_o = {1'b0, flags_in[3:0]};
        if (both_nonzero) begin
            // Saturated shifts MUST return exactly1, not shifted-at-limit|1.
            if (clamped) begin
                y = word_t'(1);
                alignment_tail = 1'b1;
            end else if (sf_equal) begin
                y = equal_small;
            end else begin
                y = aligned_small;
                alignment_tail = lost_tail;
            end
        end
        if (is_nar) begin
            x = '0;
            y = '0;
            sf_base = '0;
            sign_base = 1'b1;
            subtract = 1'b0;
            alignment_tail = 1'b0;
            is_zero = 1'b0;
            flags_o = 5'b10000;
        end else if (is_zero) begin
            x = '0;
            y = '0;
            sf_base = '0;
            sign_base = 1'b0;
            subtract = 1'b0;
            alignment_tail = 1'b0;
        end
    end
endmodule
