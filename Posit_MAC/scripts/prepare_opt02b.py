"""Prepare the isolated OPT-02b candidate and reproducible verification inputs."""
from pathlib import Path
import hashlib
import json
import shutil

R=Path(__file__).resolve().parents[1]
O=R/'results/opt02b_20261017'
assert not (O/'source/candidate').exists(), 'Do not overwrite frozen sources'
old=(O/'source/baseline/posit_add_align.sv').read_text()
header=old[:old.index('    localparam int ADD_W')]
header=header.replace('// $Revision: 1.0 $','// $Revision: OPT-02b candidate $').replace('// $Log: W10 implementation, SPEC 5.8-A..D. $','// $Log: 2026-10-17 parallel deltas, sf-only shifter, prefix-OR jam. $')
body='''    localparam int ADD_W = F + 5;
    localparam int SHIFT_W = $clog2(ADD_W);
    localparam int LOOKUP_W = 1 << SHIFT_W;
    typedef logic [ADD_W-1:0] word_t;
    typedef logic signed [SF_W:0] delta_t;
    typedef logic [SHIFT_W-1:0] shift_t;

    wire [ADD_W-1:0] seed_a;
    wire [ADD_W-1:0] seed_b;
    wire [ADD_W-2:0] shift_seed;
    wire [ADD_W-2:0] shifted_upper;
    wire fill_val = 1'b0;
    wire signed [SF_W:0] diff_ab;
    wire signed [SF_W:0] diff_ba;
    wire sf_a_lt_b;
    wire sf_equal;
    wire frac_a_ge_b;
    wire choose_a;
    wire both_nonzero;
    wire clamp_ab;
    wire clamp_ba;
    wire clamped;
    wire [SHIFT_W-1:0] shift_ab;
    wire [SHIFT_W-1:0] shift_ba;
    wire [SHIFT_W-1:0] shift_amount;
    wire [F+3:0] lo_or_a;
    wire [F+3:0] lo_or_b;
    wire [LOOKUP_W-1:0] tail_a;
    wire [LOOKUP_W-1:0] tail_b;
    wire [LOOKUP_W-1:0] jam_a;
    wire [LOOKUP_W-1:0] jam_b;
    wire lost_tail;
    wire jam_bit;
    wire [ADD_W-1:0] equal_small;
    wire [ADD_W-1:0] aligned_small;

    generate
        if (F != NB - 3 - ES || F < 2 || NB > 32 || NB < 4 || ES < 0
            || SF_W < $clog2(64'd4 * (longint'(NB) - 64'd2)
                * (64'd1 << ES) + 64'd4) + 1) begin : g_invalid
            initial $fatal(1, "posit_add_align: unsupported parameters");
        end
    endgenerate

    // Full signed precision is retained before either subtraction.
    assign diff_ab = delta_t'(a_sf) - delta_t'(b_sf);
    assign diff_ba = delta_t'(b_sf) - delta_t'(a_sf);
    assign sf_a_lt_b = diff_ab[SF_W];
    assign sf_equal = a_sf == b_sf;
    assign clamp_ab = diff_ab > (delta_t'(F) + delta_t'(2));
    assign clamp_ba = diff_ba > (delta_t'(F) + delta_t'(2));
    assign shift_ab = clamp_ab ? shift_t'(F + 2) : shift_t'(diff_ab);
    assign shift_ba = clamp_ba ? shift_t'(F + 2) : shift_t'(diff_ba);
    assign shift_amount = sf_a_lt_b ? shift_ba : shift_ab;
    assign clamped = sf_a_lt_b ? clamp_ba : clamp_ab;

    assign seed_a = {1'b0, 1'b1, a_frac, 3'b000};
    assign seed_b = {1'b0, 1'b1, b_frac, 3'b000};
    assign frac_a_ge_b = a_frac >= b_frac;
    assign both_nonzero = !a_is_zero && !b_is_zero;
    assign choose_a = !a_is_zero
                    && (b_is_zero || (!sf_a_lt_b && (!sf_equal || frac_a_ge_b)));

    // Shifter data selection NEVER depends on the fraction comparison.
    // Bit0 is generated by a parallel prefix lookup, so shift only upper bits.
    assign shift_seed = sf_a_lt_b ? seed_a[ADD_W-1:1]
                                 : seed_b[ADD_W-1:1];
    dyn_right_shifter #(
        .N(ADD_W - 1),
        .SHIFT_W(SHIFT_W),
        .ARITH(1'b0)
    ) u_align_shift (
        .in(shift_seed),
        .b(shift_amount),
        .fill_val(fill_val),
        .out(shifted_upper)
    );

    // Fixed reduction expressions, not a serial lo_or[k-1] recurrence.
    // seed[2:0]=0. Legal shift <=F+2; jam needs the prefix through F+3.
    generate
        for (genvar k = 0; k <= F+3; k = k+1) begin : g_prefix
            if (k <= 3) begin : g_zero
                assign lo_or_a[k] = 1'b0;
                assign lo_or_b[k] = 1'b0;
            end else begin : g_fraction
                assign lo_or_a[k] = |a_frac[k-4:0];
                assign lo_or_b[k] = |b_frac[k-4:0];
            end
        end
        // Padding keeps dynamic bit-select width valid for every legal F.
        // jam[s]=lo_or[s+1] is fixed wiring: no run-time index increment.
        for (genvar k = 0; k < LOOKUP_W; k = k+1) begin : g_lookup
            if (k <= F+2) begin : g_live
                assign tail_a[k] = lo_or_a[k];
                assign tail_b[k] = lo_or_b[k];
                assign jam_a[k] = lo_or_a[k+1];
                assign jam_b[k] = lo_or_b[k+1];
            end else begin : g_pad
                assign tail_a[k] = 1'b0;
                assign tail_b[k] = 1'b0;
                assign jam_a[k] = 1'b0;
                assign jam_b[k] = 1'b0;
            end
        end
    endgenerate
    assign lost_tail = sf_a_lt_b ? tail_a[shift_amount] : tail_b[shift_amount];
    assign jam_bit = sf_a_lt_b ? jam_a[shift_amount] : jam_b[shift_amount];
    assign equal_small = frac_a_ge_b ? seed_b : seed_a;
    assign aligned_small = {shifted_upper, jam_bit};

    always_comb begin
        x = choose_a ? seed_a : seed_b;
        sf_base = choose_a ? a_sf : b_sf;
        sign_base = choose_a ? a_sign : b_sign;
        y = '0;
        subtract = both_nonzero && (a_sign != b_sign);
        alignment_tail = 1'b0;
        is_zero = a_is_zero && b_is_zero;
        is_nar = a_is_nar || b_is_nar || flags_in[4];
        flags_o = {1'b0, flags_in[3:0]};
        if (both_nonzero) begin
            // Saturated shifts MUST return exactly1, not shifted-at-limit|1.
            if (clamped) begin
                y = word_t'(1);
                alignment_tail = 1'b1;
            end else if (sf_equal) begin
                y = equal_small;
            end else begin
                y = aligned_small;
                alignment_tail = lost_tail;
            end
        end
        if (is_nar) begin
            x = '0;
            y = '0;
            sf_base = '0;
            sign_base = 1'b1;
            subtract = 1'b0;
            alignment_tail = 1'b0;
            is_zero = 1'b0;
            flags_o = 5'b10000;
        end else if (is_zero) begin
            x = '0;
            y = '0;
            sf_base = '0;
            sign_base = 1'b0;
            subtract = 1'b0;
            alignment_tail = 1'b0;
        end
    end
endmodule
// End of posit_add_align.sv (OPT-02b candidate).
'''
candidate=R/'rtl/candidates/adder/opt02b/posit_add_align.sv'
candidate.write_text(header+body,encoding='utf-8')
shutil.copytree(O/'source/baseline',O/'source/candidate')
shutil.copyfile(candidate,O/'source/candidate/posit_add_align.sv')
(O/'posit_add_align_before.sv').write_text(old.replace('module posit_add_align #(','module posit_add_align_before #('),encoding='utf-8')
checker=(R/'tb/align_refactor_checker.sv').read_text()
checker=checker.replace('align_refactor_checker','opt02b_align_checker').replace('posit_add_align #(','posit_add_align_before #(').replace('posit_add_align_candidate #(','posit_add_align #(').replace('20261015','20261017')
point='        for (int trial=0;trial<RANDOM_CASES;trial++) begin'
extra='''        // Each low bit at every shift, both scale directions and all signs.
        a_is_zero=0; b_is_zero=0; a_is_nar=0; b_is_nar=0; flags_in=0;
        for (int d=0;d<=F+3;d++) for (int bitpos=0;bitpos<F;bitpos++) begin
            for (int signs=0;signs<4;signs++) begin
                a_sign=signs[0]; b_sign=signs[1];
                a_frac=frac_t'(1) << bitpos; b_frac=a_frac;
                a_sf=sf_t'(d); b_sf=0; check();
                a_sf=0; b_sf=sf_t'(d); check();
                a_frac='0; b_frac=frac_t'(1) << bitpos; check();
                a_sf=sf_t'(d); b_sf=0; check();
            end
        end
'''
checker=checker.replace(point,extra+point)
(R/'tb/opt02b_align_checker.sv').write_text(checker,encoding='utf-8')
top=(R/'tb/tb_align_refactor.sv').read_text().replace('tb_align_refactor','tb_opt02b_align').replace('align_refactor_checker','opt02b_align_checker')
(R/'tb/tb_opt02b_align.sv').write_text(top,encoding='utf-8')
hashes={p.relative_to(O).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in (O/'source').rglob('*') if p.is_file()}
(O/'source_sha256.json').write_text(json.dumps(hashes,indent=2)+'\n')
print('OPT02B_PREPARED')
